#!/usr/bin/env python3
"""followuidmagiceditor: set head and tail points of follow-UID (跟随) magic APNGs.

    main.py

Open a directory of magic APNGs generated by gfxres2apng.py with File > Open Magic Dir,
nothing is shown before that. Head and tail are stored in the file names, clicks only
edit them in memory, File > Save renames the edited files. Repack magic.zsdb from the
directory after saving.

The followuidmagiceditor python module must be in this script's directory, as installed.
"""

import importlib
import os
import sys

from PySide6.QtCore import Qt, QTimer
from PySide6.QtGui import QAction, QActionGroup, QKeySequence
from PySide6.QtWidgets import (QApplication, QFileDialog, QHBoxLayout, QLabel, QMainWindow, QMessageBox,
                               QPushButton, QScrollArea, QSlider, QSplitter, QVBoxLayout, QWidget)

from infopane import InfoPane
from magiccanvas import MagicCanvas
from magicdir import MagicDir

FOLLOW_STAGE = "运行"
FOLLOW_TYPE = "跟随"
FRAME_INTERVAL_MS = 100


def import_dbcom():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, script_dir)
    try:
        return importlib.import_module("followuidmagiceditor")
    except ImportError as e:
        raise ImportError(f"can't import followuidmagiceditor module from {script_dir}: {e}\n"
                          "build target followuidmagiceditor with build.py --python <python with nanobind>, "
                          "then install it") from e
    finally:
        sys.path.remove(script_dir)


def follow_magics(dbcom):
    """[(magic name, resolved 运行 entry)] of all magics whose 运行 stage is a 跟随 gfx."""
    result = []
    for name in dbcom.magic_names():
        entry = dbcom.magic_gfx_entry(name, FOLLOW_STAGE)
        if entry and entry["type"] == FOLLOW_TYPE and entry["gfxID"] is not None:
            result.append((name, entry))
    return result


class MainWindow(QMainWindow):
    def __init__(self, magics, records):
        super().__init__()
        self.setWindowTitle("followuidmagiceditor")
        self.resize(1300, 850)

        self.magics = magics
        self.records = records
        self.magic_dir = None
        self.current = None
        self.frame_count = 0
        self.hover = None

        self.canvas = MagicCanvas()
        self.canvas.pointPicked.connect(self.on_point_picked)
        self.canvas.hoverChanged.connect(self.on_hover_changed)

        self.info_pane = InfoPane()
        self.info_pane.direction_table.directionSelected.connect(self.canvas.set_selected)

        self.play_button = QPushButton("Play")
        self.play_button.setCheckable(True)
        self.play_button.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.play_button.toggled.connect(self.on_play_toggled)

        self.slider = QSlider(Qt.Orientation.Horizontal)
        self.slider.valueChanged.connect(self.on_frame_changed)

        self.frame_label = QLabel()

        controls = QHBoxLayout()
        controls.addWidget(self.play_button)
        controls.addWidget(self.slider, 1)
        controls.addWidget(self.frame_label)

        layout = QVBoxLayout()
        layout.addWidget(self.canvas, 1)
        layout.addLayout(controls)

        view = QWidget()
        view.setLayout(layout)

        info_scroll = QScrollArea()
        info_scroll.setWidgetResizable(True)
        info_scroll.setWidget(self.info_pane)
        info_scroll.setMinimumWidth(360)

        splitter = QSplitter(Qt.Orientation.Horizontal)
        splitter.addWidget(view)
        splitter.addWidget(info_scroll)
        splitter.setStretchFactor(0, 1)
        splitter.setSizes([900, 400])
        self.setCentralWidget(splitter)

        self.timer = QTimer(self)
        self.timer.setInterval(FRAME_INTERVAL_MS)
        self.timer.timeout.connect(lambda: self.slider.setValue((self.slider.value() + 1) % max(1, self.frame_count)))

        self._build_menus()
        self.update_dirty()

    def _build_menus(self):
        file_menu = self.menuBar().addMenu("&File")
        file_menu.addAction("&Open Magic Dir...", QKeySequence.StandardKey.Open, self.choose_magic_dir)
        self.save_action = file_menu.addAction("&Save", QKeySequence.StandardKey.Save, self.save)
        self.revert_action = file_menu.addAction("Re&vert", self.revert)
        file_menu.addAction("&Reload", QKeySequence.StandardKey.Refresh, self.reload)
        file_menu.addSeparator()
        file_menu.addAction("&Quit", QKeySequence.StandardKey.Quit, self.close)

        edit_menu = self.menuBar().addMenu("&Edit")
        self.non_rotate_action = edit_menu.addAction("&Non-Rotate")
        self.non_rotate_action.setShortcut(Qt.Key.Key_N)
        self.non_rotate_action.setCheckable(True)
        self.non_rotate_action.triggered.connect(self.on_non_rotate_triggered)
        self.non_rotate_action.setStatusTip("head == tail in all directions of the current magic, never rotated")

        magic_menu = self.menuBar().addMenu("&Magic")
        self.magic_actions = {}
        group = QActionGroup(self)

        for name, entry in self.magics:
            text = f"{name}\t{entry['gfxID']:07X} x{entry['gfxDirType']}"
            if entry["ref"]:
                text += f" → {entry['ref']['name']}"

            action = QAction(text, self, checkable=True)
            action.triggered.connect(lambda _=False, n=name: self.select_magic(n))
            group.addAction(action)
            magic_menu.addAction(action)
            self.magic_actions[name] = action

        view_menu = self.menuBar().addMenu("&View")
        play_action = view_menu.addAction("&Play/Pause", Qt.Key.Key_Space, self.play_button.toggle)
        play_action.setShortcutContext(Qt.ShortcutContext.ApplicationShortcut)
        view_menu.addAction("Reset &View", self.canvas.reset_view)

    def dirty_count(self):
        return len(self.magic_dir.dirty_seqs()) if self.magic_dir else 0

    def update_dirty(self):
        count = self.dirty_count()
        self.save_action.setEnabled(count > 0)
        self.revert_action.setEnabled(count > 0)
        self.non_rotate_action.setEnabled(self.magic_dir is not None and self.current is not None)
        self.non_rotate_action.setChecked(self.non_rotate())

        title = "followuidmagiceditor"
        if self.magic_dir:
            title += f" - {self.magic_dir.path}"
        if count:
            title += f" [{count} unsaved]"
        self.setWindowTitle(title)
        self.canvas.update()
        self.update_info()

    def confirm_discard(self):
        """True if there is no unsaved edit, or the user saved or discarded them."""
        count = self.dirty_count()
        if count == 0:
            return True

        buttons = QMessageBox.StandardButton
        answer = QMessageBox.question(self, "Unsaved Edits", f"{count} APNG(s) have unsaved head/tail edits.",
                                      buttons.Save | buttons.Discard | buttons.Cancel, buttons.Save)
        if answer == buttons.Save:
            return self.save()
        return answer == buttons.Discard

    def save(self):
        if not self.magic_dir:
            return True

        try:
            renames = self.magic_dir.save()
        except OSError as e:
            QMessageBox.critical(self, "Save", str(e))
            self.update_dirty()
            return False

        self.update_dirty()
        self.statusBar().showMessage(f"renamed {len(renames)} APNG(s)")
        return True

    def revert(self):
        if self.magic_dir:
            self.magic_dir.revert()
            self.update_dirty()
            self.refresh()

    def closeEvent(self, event):
        if self.confirm_discard():
            event.accept()
        else:
            event.ignore()

    def choose_magic_dir(self):
        if not self.confirm_discard():
            return

        path = QFileDialog.getExistingDirectory(self, "Magic APNG Dir", self.magic_dir.path if self.magic_dir else "")
        if path:
            self.open_magic_dir(path)

    def open_magic_dir(self, path):
        try:
            self.magic_dir = MagicDir(path)
        except (OSError, ValueError) as e:
            QMessageBox.critical(self, "Open Magic Dir", str(e))
            return

        self.update_dirty()
        self.refresh()

    def reload(self):
        if self.magic_dir and self.confirm_discard():
            self.open_magic_dir(self.magic_dir.path)

    def select_magic(self, name):
        entry = dict(self.magics)[name]
        self.current = (name, entry)
        self.magic_actions[name].setChecked(True)
        self.refresh()

    def current_seqs(self):
        if self.magic_dir is None or self.current is None:
            return []
        entry = self.current[1]
        return [self.magic_dir.get(entry["gfxID"], d) for d in range(entry["gfxDirType"])]

    def refresh(self):
        """Rebuild the view after the magic, the magic dir or the gfx mode changes."""
        if self.magic_dir is None or self.current is None:
            self.canvas.set_magic(None, None, 0)
            self.frame_count = 0
        else:
            entry = self.current[1]
            self.canvas.set_magic(self.magic_dir, entry["gfxID"], entry["gfxDirType"])
            self.frame_count = entry["frameCount"] or max((len(s.frames()) for s in self.current_seqs() if s),
                                                          default=0)

        self.info_pane.direction_table.clear_selection()
        self.slider.setRange(0, max(0, self.frame_count - 1))
        self.on_frame_changed(self.slider.value())
        self.update_dirty()

    def update_info(self):
        """Update the info pane after any edit, refresh() or hover change."""
        pane = self.info_pane
        pane.dir_section.update_dir(self.magic_dir)

        if self.magic_dir is None or self.current is None:
            pane.magic_section.update_magic(None, None, None, None)
            pane.entry_section.update_entry(None, 0, False, [])
            pane.direction_table.update_seqs([])
        else:
            name, entry = self.current
            shared = [n for n, e in self.magics if n != name and e["gfxID"] == entry["gfxID"]]
            seqs = self.current_seqs()

            pane.magic_section.update_magic(name, self.records[name], entry, shared)
            pane.entry_section.update_entry(entry, self.frame_count, self.non_rotate(),
                                            [d for d, s in enumerate(seqs) if s is None])
            pane.direction_table.update_seqs(seqs)

        direction, mouse = self.hover if self.hover else (None, None)
        pane.hover_section.update_hover(self.canvas.seq(direction) if self.hover else None, direction, mouse)

    def on_hover_changed(self, hover):
        self.hover = hover
        self.info_pane.hover_section.update_hover(self.canvas.seq(hover[0]) if hover else None,
                                                  *(hover if hover else (None, None)))
        if hover is None:
            self.statusBar().clearMessage()
        else:
            seq = self.canvas.seq(hover[0])
            self.statusBar().showMessage(f"dir {hover[0]}: {hover[1]}, head {seq.head}, tail {seq.tail}, "
                                         f"{seq.name}{' (unsaved)' if seq.dirty else ''}")

    def on_frame_changed(self, frame):
        self.canvas.set_frame(frame)
        self.frame_label.setText(f"{frame + 1 if self.frame_count else 0}/{self.frame_count}")

    def on_play_toggled(self, playing):
        self.play_button.setText("Pause" if playing else "Play")
        if playing:
            self.timer.start()
        else:
            self.timer.stop()

    def non_rotate(self):
        if self.magic_dir is None or self.current is None:
            return False
        entry = self.current[1]
        return self.magic_dir.is_non_rotate(entry["gfxID"], entry["gfxDirType"])

    def on_non_rotate_triggered(self, on):
        if self.magic_dir is None or self.current is None:
            return

        entry = self.current[1]
        self.magic_dir.set_non_rotate(entry["gfxID"], entry["gfxDirType"], on)
        self.refresh()

    def on_point_picked(self, direction, which, point):
        seq = self.canvas.seq(direction)
        if seq is None:
            return

        if self.non_rotate():
            self.magic_dir.set_points(seq, head=point, tail=point)
        else:
            self.magic_dir.set_points(seq, **{which: point})
        self.statusBar().showMessage(f"dir {direction}: {which} {point}, unsaved")
        self.update_dirty()


def main():
    app = QApplication(sys.argv)

    try:
        dbcom = import_dbcom()
    except ImportError as e:
        QMessageBox.critical(None, "followuidmagiceditor", str(e))
        return 1

    magics = follow_magics(dbcom)
    window = MainWindow(magics, {name: dbcom.magic_record(name) for name, _ in magics})
    if window.magics:
        window.select_magic(window.magics[0][0])
    else:
        window.refresh()

    window.show()
    return app.exec()


if __name__ == "__main__":
    sys.exit(main())
